// ---- SharedBuffer::Release ----------------------------------------------------------------------------------
// A handle to a buffer several owners share: {int references; ...; +0xc data (an aligned block)}. Releasing
// drops one reference; the last one frees the data and the buffer itself.

struct SharedBuffer {
    int32_t references;
    char unknown[8];
    void *data;   // +0xc
};

static volatile long g_releases;

static void __fastcall shared_release(SharedBuffer **handle) {
    g_releases++;
    (*handle)->references--;
    SharedBuffer *b = *handle;
    if (b->references == 0 && b) {
        memory_free_aligned(b->data);
        memory_free(b);
    }
}

