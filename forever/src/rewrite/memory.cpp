// ---- OwnedPair::Free: free the two aligned blocks an object owns (+0 and +4), leaving the pointers ---------

static volatile long g_pairs;

static void __fastcall owned_pair_free(void **owned) {
    g_pairs++;
    if (owned[0]) memory_free_aligned(owned[0]);
    if (owned[1]) memory_free_aligned(owned[1]);
}

