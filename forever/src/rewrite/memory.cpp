// Small memory helpers the compiler stamped out once per type: owned pointers and shared, reference-counted
// buffers. Each has hundreds of copies in RCT3plus.exe, all the same code; one rewrite replaces them all.
#include "rewrite.h"

static void(__cdecl *const memory_free)(void *) = (void(__cdecl *)(void *))0xbce000;                // free
static void(__cdecl *const memory_free_aligned)(void *) = (void(__cdecl *)(void *))0xbce010;        // free of a 16-byte aligned block

// ---- OwnedPointer::Reset: free what the pointer owns (an aligned block) and clear it ----------------------

static volatile long g_resets;

static void __fastcall owned_reset(void **owned) {
    g_resets++;
    if (*owned) {
        memory_free_aligned(*owned);
        *owned = nullptr;
    }
}

