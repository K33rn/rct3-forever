"""Small functions whose whole behaviour is plain from their few instructions, written to docs/notes/small.md.

usage: python tools/trivial.py "<game folder>\\RCT3plus.exe"

Each function of a few instructions is matched against the shapes a compiler makes for the simplest functions, and
described exactly when it matches one; anything else is left for reading by hand:
  - empty: `ret` (or `ret n`)
  - a constant: `xor eax, eax` / `mov eax, imm` / `mov al, imm`, then `ret`
  - a member: `mov eax, [ecx + n]` (or the byte / word / float forms, or `lea eax, [ecx + n]` for its address), `ret`
  - a global: `mov eax, [g]` (or its address), `ret`
  - a setter: `mov eax, [esp + 4]`, `mov [ecx + n], eax`, `ret 4` (also bytes, and constants stored)
  - a thunk: `jmp f`, or `mov ecx, [ecx + n]` / `add ecx, n` / `lea ecx, [ecx + n]` then `jmp f`
  - a virtual call through the object's table: `mov eax, [ecx]`, `jmp [eax + n]`
  - a scalar deleting destructor: calls the destructor, then frees the object when its flag argument has bit 0 set
Names are taken from the notes when the target has one.
"""
import csv
import glob
import os
import re
import sys

import capstone
import pefile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 0x400000
FREE = {0xDDFBD2, 0xBCE000, 0xBCE010, 0xDDFBDC}


def names():
    n = {}
    for p in glob.glob(os.path.join(HERE, 'docs', 'notes', '*.md')):
        if os.path.basename(p) == 'small.md':
            continue
        for m in re.finditer(r'^\| `0x([0-9a-fA-F]+)` \| ([^|]+?) \|', open(p, encoding='utf-8').read(), re.M):
            n[int(m.group(1), 16)] = m.group(2)
    for r in csv.DictReader(open(os.path.join(HERE, 'docs', 'functions.csv'))):
        if r['status'] in ('rewritten', 'library') and r['name']:
            n[int(r['address'], 16)] = r['name']
    return n


def main():
    pe = pefile.PE(sys.argv[1], fast_load=True)
    mem = pe.get_memory_mapped_image()
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    funcs = {int(r['address'], 16): r for r in csv.DictReader(open(os.path.join(HERE, 'docs', 'functions.csv')))}
    nm = names()
    described = set(nm)

    def fn(t):
        return f'`{t:#x}`' + (f' ({nm[t]})' if t in nm else '')

    rows = []
    for va, r in sorted(funcs.items()):
        n = int(r['size'])
        if r['status'] not in ('to do', 'documented') or va in described or n > 40:
            continue
        ins = list(md.disasm(mem[va - BASE:va - BASE + n], va))
        while ins and ins[-1].mnemonic in ('int3', 'nop'):
            ins.pop()
        if not ins:
            continue
        ops = [(i.mnemonic, i.op_str) for i in ins]
        text = ' ; '.join(f'{m} {o}'.strip() for m, o in ops)
        d = describe(ins, ops, fn)
        if d:
            rows.append(f'| `{va:#x}` | {d[0]} | {d[1]} |')
    out = ['# Small functions', '',
           'Generated by `tools/trivial.py`: functions of a few instructions whose whole behaviour is one of the',
           'simplest shapes a compiler makes (see the script). Offsets are from the object the function is called on',
           '(`this`, passed in `ecx`).', '',
           '| Address | Name | What it does |', '|---|---|---|'] + rows
    open(os.path.join(HERE, 'docs', 'notes', 'small.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(len(rows), 'small functions')


def mem_op(i, k):
    op = i.operands[k]
    return op if op.type == capstone.x86.X86_OP_MEM else None


def imm(i, k=0):
    op = i.operands[k]
    return op.imm & 0xffffffff if op.type == capstone.x86.X86_OP_IMM else None


def ret_args(i):
    v = imm(i) if i.operands else None
    return f', taking {v // 4} argument{"s" if v // 4 != 1 else ""} off the stack' if v else ''


def describe(ins, ops, fn):
    X = capstone.x86
    m0 = ops[0][0]
    last = ins[-1]
    # empty
    if len(ins) == 1 and m0 == 'ret':
        return 'Empty', 'Does nothing' + ret_args(ins[0])
    # thunk
    if len(ins) == 1 and m0 == 'jmp' and imm(ins[0]) is not None:
        return 'Thunk', f'Jumps to {fn(imm(ins[0]))}'
    # virtual dispatch: mov eax,[ecx] ; jmp [eax+n]
    if len(ins) == 2 and ops[0] == ('mov', 'eax, dword ptr [ecx]') and ins[1].mnemonic == 'jmp' and mem_op(ins[1], 0):
        return 'Virtual thunk', f'Calls the object\'s virtual function at slot {ins[1].operands[0].mem.disp // 4}'
    # this adjustment then jump
    if len(ins) == 2 and ins[1].mnemonic == 'jmp' and imm(ins[1]) is not None:
        o = ins[0]
        if o.mnemonic == 'mov' and o.op_str.startswith('ecx, dword ptr [ecx'):
            return 'Thunk', f'Calls {fn(imm(ins[1]))} on the object at +{o.operands[1].mem.disp:#x}'
        if o.mnemonic in ('add', 'sub') and o.op_str.startswith('ecx, '):
            v = imm(o, 1)
            if v is not None:
                v = v if o.mnemonic == 'add' else -v
                v = v - (1 << 32) if v >= 1 << 31 else v
                return 'Thunk', f'Calls {fn(imm(ins[1]))} on `this` {v:+#x}'
        if o.mnemonic == 'lea' and o.op_str.startswith('ecx, [ecx'):
            return 'Thunk', f'Calls {fn(imm(ins[1]))} on `this` {o.operands[1].mem.disp:+#x}'
    if last.mnemonic != 'ret':
        return None
    body = ins[:-1]
    ra = ret_args(last)
    # constants
    if len(body) == 1:
        b = body[0]
        if b.mnemonic == 'xor' and b.op_str == 'eax, eax':
            return 'Returns 0', 'Returns 0 (or false / null)' + ra
        if b.mnemonic == 'mov' and b.op_str.startswith(('eax, ', 'al, ')) and imm(b, 1) is not None:
            v = imm(b, 1)
            if b.op_str.startswith('al'):
                return f'Returns {v}', ('Returns true' if v == 1 else f'Returns {v}') + ra
            return f'Returns {v:#x}', f'Returns {v:#x}' + ra
        if b.mnemonic in ('mov', 'movzx', 'movsx', 'fld', 'lea') and len(b.operands) >= 1:
            src = b.operands[-1]
            if src.type == X.X86_OP_MEM:
                kind = {'fld': 'float ', 'movzx': '', 'movsx': ''}.get(b.mnemonic, '')
                size = {1: 'byte', 2: '16-bit value', 4: 'value', 8: 'double'}.get(src.size, 'value')
                if b.mnemonic == 'fld':
                    size = 'float' if src.size == 4 else 'double'
                if b.mnemonic == 'lea' and src.mem.base == X.X86_REG_ECX:
                    return f'Member +{src.mem.disp:#x} address', f'Returns the address of the member at +{src.mem.disp:#x}' + ra
                if src.mem.base == X.X86_REG_ECX and src.mem.index == 0:
                    return f'Get +{src.mem.disp:#x}', f'Returns the {size} at +{src.mem.disp:#x}' + ra
                if src.mem.base == 0 and src.mem.index == 0:
                    g = src.mem.disp & 0xffffffff
                    if b.mnemonic == 'lea':
                        return f'Global {g:#x} address', f'Returns the address `{g:#x}`' + ra
                    return f'Get global {g:#x}', f'Returns the {size} in the global `{g:#x}`' + ra
            if b.mnemonic == 'mov' and b.op_str.startswith('eax, ') and imm(b, 1) is not None:
                v = imm(b, 1)
                return f'Returns {v:#x}', f'Returns {v:#x}' + ra
    # setters: mov eax/reg,[esp+4] ; mov [ecx+n], reg  (or a constant stored)
    if 1 <= len(body) <= 2:
        stores = [b for b in body if b.mnemonic == 'mov' and mem_op(b, 0) and b.operands[0].mem.base == X.X86_REG_ECX]
        if len(stores) == 1:
            s = stores[0]
            off = s.operands[0].mem.disp
            src = s.operands[1]
            if src.type == X.X86_OP_IMM:
                v = src.imm & 0xffffffff
                if len(body) == 1 and off == 0 and 0xF26000 <= v < 0x10E7000:
                    return 'Set table', f"Sets the object's virtual function table to `{v:#x}`" + ra
                if len(body) == 1:
                    return f'Set +{off:#x}', f'Sets the member at +{off:#x} to {src.imm & 0xffffffff:#x}' + ra
            elif len(body) == 2 and body[0].mnemonic in ('mov', 'movzx') and mem_op(body[0], 1) and \
                    body[0].operands[1].mem.base == X.X86_REG_ESP and body[0].operands[1].mem.disp == 4:
                return f'Set +{off:#x}', f'Sets the member at +{off:#x} to its argument' + ra
    # scalar deleting destructor
    calls = [i for i in ins if i.mnemonic == 'call' and imm(i) is not None]
    shape = [i.mnemonic for i in ins]
    if shape == ['push', 'mov', 'call', 'test', 'je', 'push', 'call', 'add', 'mov', 'pop', 'ret'] and             ins[1].op_str == 'esi, ecx' and imm(calls[1]) in FREE and ins[3].op_str == 'byte ptr [esp + 8], 1':
        return 'Deleting destructor', (f'Destroys the object ({fn(imm(calls[0]))}) and frees its memory when '
                                       f'its argument has bit 0 set; returns the object' + ra)
    return None


if __name__ == '__main__':
    main()
