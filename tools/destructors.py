"""The game's destructors, written to docs/notes/destructors.md.

usage: python tools/destructors.py "<game folder>\\RCT3plus.exe"     (after tools/trivial.py)

Every class with a virtual destructor has a small "deleting destructor" (listed in small.md) that calls the real
destructor and then frees the object. A destructor puts back its class's virtual function table(s), destroys the
members that need it (object references, texts, owned blocks, arrays, other objects) and runs its base class's
destructor. This reads each destructor's instructions and lists exactly that: the tables it stores, the calls it makes
(by name where the notes have one) and the last call (the base class's destructor, when it is one too).
"""
import collections
import csv
import glob
import os
import re
import sys

import capstone
import pefile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 0x400000


def main():
    pe = pefile.PE(sys.argv[1], fast_load=True)
    mem = pe.get_memory_mapped_image()
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    funcs = {int(r['address'], 16): r for r in csv.DictReader(open(os.path.join(HERE, 'docs', 'functions.csv')))}
    notes = {}
    for p in glob.glob(os.path.join(HERE, 'docs', 'notes', '*.md')):
        if os.path.basename(p) == 'destructors.md':
            continue
        for m in re.finditer(r'^\| `0x([0-9a-fA-F]+)` \| ([^|]+?) \|', open(p, encoding='utf-8').read(), re.M):
            notes[int(m.group(1), 16)] = m.group(2)
    for r in funcs.values():
        if r['status'] in ('rewritten', 'library') and r['name']:
            notes[int(r['address'], 16)] = r['name']
    vt_class = {int(m.group(2), 16): m.group(1) for m in re.finditer(
        r'\| (\w+)::\1 \| Constructor of \w+, virtual function table `0x([0-9a-f]+)`',
        open(os.path.join(HERE, 'docs', 'notes', 'classes.md'), encoding='utf-8').read())}
    small = open(os.path.join(HERE, 'docs', 'notes', 'small.md'), encoding='utf-8').read()
    callers = collections.defaultdict(list)
    for m in re.finditer(r'^\| `(0x[0-9a-f]+)` \| Deleting destructor \| Destroys the object \(`(0x[0-9a-f]+)`', small, re.M):
        callers[int(m.group(2), 16)].append(int(m.group(1), 16))
    dtors = set(callers)

    def name(t):
        if t in notes and not re.match(r'(Empty|Thunk|Virtual thunk|Set |Get |Returns|Member|Global|Deleting)', notes[t]):
            return notes[t]
        if t in dtors:
            return f'destructor `{t:#x}`'
        return f'`{t:#x}`'

    rows = []
    for va in sorted(dtors):
        r = funcs.get(va)
        if not r or r['status'] not in ('to do', 'documented') or (va in notes):
            continue
        n = int(r['size'])
        ins = list(md.disasm(mem[va - BASE:va - BASE + n], va))
        tables, calls = [], []
        for i in ins:
            if i.mnemonic == 'mov' and len(i.operands) == 2 and i.operands[0].type == capstone.x86.X86_OP_MEM and \
                    i.operands[1].type == capstone.x86.X86_OP_IMM:
                v = i.operands[1].imm & 0xffffffff
                if 0xF26000 <= v < 0x10E7000 and v not in tables:
                    tables.append(v)
            if i.mnemonic == 'call' and i.operands[0].type == capstone.x86.X86_OP_IMM:
                calls.append(i.operands[0].imm & 0xffffffff)
        cls = next((vt_class[t] for t in tables if t in vt_class), None)
        what = f'Destructor of {cls}' if cls else 'Destructor'
        parts = []
        if tables:
            parts.append('puts back the virtual function table' + ('s ' if len(tables) > 1 else ' ') +
                         ', '.join(f'`{t:#x}`' for t in tables[:4]))
        base = calls[-1] if calls and (calls[-1] in dtors or 'destructor' in name(calls[-1]).lower() or
                                       '~' in name(calls[-1])) else None
        member = [c for c in calls if c != base]
        cnt = collections.Counter(name(c) for c in member)
        if cnt:
            parts.append('destroys its members (' + ', '.join(f'{k}' + (f' x{v}' if v > 1 else '')
                                                            for k, v in cnt.most_common(8)) +
                         (', ...' if len(cnt) > 8 else '') + ')')
        if base:
            parts.append(f'then runs {name(base)}')
        dd = ', '.join(f'`{c:#x}`' for c in callers[va][:3])
        rows.append(f'| `{va:#x}` | {cls + "::~" + cls if cls else "Destructor"} | {what} (called by the deleting '
                    f'destructor {dd}): ' + (', '.join(parts) if parts else 'nothing else to undo') + ' |')
    out = ['# Destructors', '',
           'Generated by `tools/destructors.py`: the destructors the deleting destructors in [small.md](small.md) call,',
           'each with the tables it puts back, the member destructors and frees it runs (by name where the notes have',
           'one) and the base class destructor it ends with.', '',
           '| Address | Name | What it does |', '|---|---|---|'] + rows
    open(os.path.join(HERE, 'docs', 'notes', 'destructors.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(len(rows), 'destructors')


if __name__ == '__main__':
    main()
