"""Start-up initializers that register names, written to docs/notes/initializers.md.

usage: python tools/initializers.py "<game folder>\\RCT3plus.exe"     (uses tools/describe.py's cache)

Before main, the compiler runs one small function for each global the game defines with a value. Two common kinds:
  - a name: String("Name") (0xBEC4B0), registered as a name object (0xBECA70: kept in the table of up to 1,000 names
    at 0x13D1418) and kept in a global, then the String freed (0xBEC5E0);
  - a section: a wide string "Name" (0xBCF850) made into a named section (0x46FAD0) of the nested tree of sections
    that code enters with 0x46FC00 and leaves with 0x46F990, with its clean-up registered with atexit.
Each is recognised from its calls and described by the name it registers and the global it fills.
"""
import csv
import glob
import os
import pickle
import re
import sys

import capstone
import pefile

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = 0x400000


def main():
    a, imports = pickle.load(open(os.path.join(HERE, 'out', 'describe.cache'), 'rb'))
    funcs = {int(r['address'], 16): r for r in csv.DictReader(open(os.path.join(HERE, 'docs', 'functions.csv')))}
    pe = pefile.PE(sys.argv[1], fast_load=True)
    mem = pe.get_memory_mapped_image()
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    rows = []
    described = set()   # functions another notes file already describes
    for p in glob.glob(os.path.join(HERE, 'docs', 'notes', '*.md')):
        if os.path.basename(p) != 'initializers.md':
            described |= {int(h, 16) for h in re.findall(r'^\| `0x([0-9a-fA-F]+)`', open(p, encoding='utf-8').read(), re.M)}
    for va, i in sorted(a.items()):
        if funcs[va]['status'] not in ('to do', 'documented') or va in described or not i['strings']:
            continue
        name = i['strings'][0].strip('"')
        if 0xBECA70 in i['calls'] and 0xBEC4B0 in i['calls'] and len(i['calls']) == 3:
            target = None
            code = list(md.disasm(mem[va - BASE:va - BASE + int(funcs[va]['size'])], va))
            for k, ins in enumerate(code):
                if ins.mnemonic == 'call' and ins.operands[0].type == capstone.x86.X86_OP_IMM and \
                        ins.operands[0].imm == 0xBECA70:
                    for x in code[k + 1:k + 3]:
                        if x.mnemonic == 'mov' and x.operands[0].type == capstone.x86.X86_OP_MEM and \
                                x.operands[0].mem.base == 0 and x.op_str.endswith('eax'):
                            target = x.operands[0].mem.disp & 0xffffffff
            where = f", kept in `{target:#x}`" if target else ""
            rows.append(f'| `{va:#x}` | Name {name} | Registers the name `{name}` at start-up (`0xBECA70`){where} |')
        elif 0x46FAD0 in i['calls'] and 0xBCF850 in i['calls']:
            rows.append(f'| `{va:#x}` | Section {name} | Creates the named section `{name}` at start-up (`0x46FAD0`) '
                        f'and registers its clean-up with `atexit` |')
    out = ['# Start-up initializers', '',
           'Generated by `tools/initializers.py`: functions the compiler runs before `main` to fill in globals that',
           'register a name (`0xBECA70`) or create a named section (`0x46FAD0`; code enters a section with `0x46FC00`',
           'and leaves it with `0x46F990`). See the script for how they are recognised.', '',
           '| Address | Name | What it does |', '|---|---|---|'] + rows
    open(os.path.join(HERE, 'docs', 'notes', 'initializers.md'), 'w', encoding='utf-8', newline='\n').write(
        '\n'.join(out) + '\n')
    print(len(rows), 'initializers')


if __name__ == '__main__':
    main()
