"""The functions that build the game's windows, written to docs/notes/windows.md.

usage: python tools/windows.py "<game folder>\\RCT3plus.exe"     (run tools/describe.py once first: uses its cache)

Every window, panel and dialog in RCT3 is a tree of GUI windows. A function that builds one creates each control and
places it in the tree with Window::SetRelation (0x6B1330, or 0x6B1640, which also lays it out): as the first or
last child of another window, or before or after it. The controls are named by text keys, which the game looks up
in its text files for what is shown. So a function that places at least three controls and uses at least three
text keys builds (or rebuilds) a window, and its keys say what is in it. Functions already described by hand in
another notes file are left out.
"""
import collections
import csv
import glob
import os
import pickle
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLACE = {0x6B1330, 0x6B1640}


def main():
    a, imports = pickle.load(open(os.path.join(HERE, 'out', 'describe.cache'), 'rb'))
    funcs = {int(r['address'], 16): r for r in csv.DictReader(open(os.path.join(HERE, 'docs', 'functions.csv')))}
    described = set()
    for p in glob.glob(os.path.join(HERE, 'docs', 'notes', '*.md')):
        if os.path.basename(p) == 'windows.md':
            continue
        described |= {int(h, 16) for h in re.findall(r'^\| `0x([0-9a-fA-F]+)`', open(p, encoding='utf-8').read(), re.M)}
    callers = collections.defaultdict(set)
    for va, i in a.items():
        for c in i['calls']:
            if isinstance(c, int):
                callers[c].add(va)
    rows = []
    for va, i in a.items():
        if va in described or funcs[va]['status'] not in ('to do', 'documented'):
            continue
        placed = sum(1 for c in i['calls'] if c in PLACE)
        keys = [s for s in dict.fromkeys(i['strings'])
                if re.fullmatch(r'[A-Za-z][A-Za-z0-9_]{2,}', s) and s != '_DRA_REF_NOT_FOUND']
        if placed < 3 or len(keys) < 3:
            continue
        # the window's name: the most common first part of its keys (GameOptionsDialog_Shadows -> GameOptionsDialog)
        parts = collections.Counter(k.split('_')[0] for k in keys if '_' in k and len(k.split('_')[0]) > 3)
        name = parts.most_common(1)[0][0] if parts and parts.most_common(1)[0][1] >= 2 else None
        cl = sorted(callers.get(va, ()))
        shown = ', '.join(f'`{k}`' for k in keys[:30]) + (f' and {len(keys) - 30} more' if len(keys) > 30 else '')
        where = (' Called from ' + ', '.join(f'`{c:#x}`' for c in cl[:4]) + (' ...' if len(cl) > 4 else '') + '.') if cl \
            else ' Reached through a table of virtual functions.'
        rows.append((va, f'| `{va:#x}` | {(name + " window") if name else "Window builder"} | Builds or rebuilds a '
                         f'window: places {placed} controls in the window tree (`0x6B1330`); its text keys: {shown}.'
                         f'{where} |', int(funcs[va]['size'])))
    rows.sort()
    out = ['# Window builders', '',
           'Generated by `tools/windows.py`: the functions that build the game\'s windows, panels and dialogs, found by',
           'how they work (each control is placed in the window tree by `0x6B1330`, Window::SetRelation) and described',
           'by the text keys they use, which name the controls and look up what they show in the game\'s text files.',
           'The bigger windows are described by hand in [gui.md](gui.md).', '',
           '| Address | Name | What it does |', '|---|---|---|'] + [r for _, r, _ in rows]
    open(os.path.join(HERE, 'docs', 'notes', 'windows.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(f'{len(rows)} window builders, {sum(z for _, _, z in rows)} bytes')


if __name__ == '__main__':
    main()
