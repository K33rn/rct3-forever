"""Notes for rewritten functions that no other note describes: docs/notes/rewritten.md.

usage: python tools/rewritten_notes.py   (then tools/progress.py)
Every rewrite is checked against the game's own code, so what a rewritten function does is known exactly; this
writes that down as a notes row (from its family's description) so the notes cover it too. Rows come from the
REWRITE / REWRITE_COPIES lists and generated.inc, the same places tools/progress.py reads.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(HERE, 'tools'))
import progress  # noqa: E402

OUT = os.path.join(HERE, 'docs', 'notes', 'rewritten.md')

# family name pattern -> (description, rewrite source)
FAMILIES = [
    (r'OwnedPointer::Reset', 'Frees what the pointer owns (an aligned block) and clears it', 'memory.cpp'),
    (r'OwnedPair::Free', 'Frees the two aligned blocks an object owns (+0 and +4), leaving the pointers', 'memory.cpp'),
    (r'SharedBuffer::Release', 'Drops one reference to a shared buffer {references, ..., +0xC data}; the last one frees '
                               'the data and the buffer itself', 'memory.cpp'),
    (r'Array<(\d+)>::SetCapacity', 'Reallocates a growable array {data, capacity} of {0}-byte items to n items, keeping '
                                   'the first min(n, capacity) as they are; gives n', 'arrays.cpp'),
    (r'Array<(\d+)>::Allocate', 'Drops a growable array\'s contents ({0}-byte items) and makes room for n items, not '
                                'cleared; gives n', 'arrays.cpp'),
    (r'ListNode::Unlink', 'Takes a node {prev, next} out of its two-way list and clears it; a node not linked both ways '
                          'means the list is broken, and it stops at a breakpoint', 'lists.cpp'),
    (r'Pool::Free', 'Gives an item back to the pool for its kind (onto the free list); when every item of a pool is '
                    'free again, its blocks go back to memory', 'pools.cpp'),
    (r'ObjectRef::Construct', 'A new reference (table `0xF26AE0`) to nothing: the null handle, joined into its list of '
                              'references; gives itself', 'references.cpp'),
    (r'ObjectRef::Assign', 'Refers to what another reference refers to: leaves the old handle\'s list, gives it up, '
                           'takes the new handle and joins its list; gives itself', 'references.cpp'),
    (r'ObjectRef::DeleteTarget', 'Deletes the object referred to (if any) and refers to nothing; gives what the '
                                 'class\'s own reaction gives', 'references.cpp'),
    (r'ReferenceField::Load', 'Reads a reference field from a save file: the stored 8-byte id, turned by the loader '
                              'into the object as loaded now, and points the reference at its handle', 'references.cpp'),
    (r'StructArrayField<(\d+)>::Size', 'How many bytes an array of {0}-byte structs saves as: the length and count, '
                                       'then every struct\'s fields', 'saved_arrays.cpp'),
    (r'StructArrayField<(\d+)>::Save', 'Saves an array of {0}-byte structs: its length, count and every struct\'s '
                                       'fields in turn, keeping the running checksum', 'saved_arrays.cpp'),
    (r'ParkEntrances::Random', 'An entrance from the park\'s global list, picked with equal chances; null when the park '
                               'has none', 'park_entrances.cpp'),
]


def describe(name):
    for pat, text, src in FAMILIES:
        m = re.fullmatch(pat, name)
        if m:
            return (text.replace('{0}', m.group(1)) if m.groups() else text), src
    return None, None


def main():
    rows = progress.load()
    addrs = {int(r['address'], 16) for r in rows}
    rw = progress.rewritten()
    # rows already in other notes files count; this file's own rows are rebuilt
    if os.path.exists(OUT):
        os.remove(OUT)
    noted, _ = progress.noted(addrs)
    noted |= progress.documented(addrs)
    out, unknown = [], []
    for a in sorted(rw):
        if a in noted or a not in addrs:
            continue
        text, src = describe(rw[a])
        if text is None:
            unknown.append(f'{a:#x} {rw[a]}')
            continue
        out.append(f'| `{a:#x}` | {rw[a]} | {text} (rewritten: forever/src/rewrite/{src}) |')
    lines = ['# Rewritten functions', '',
             'Generated by `tools/rewritten_notes.py`. Functions already rewritten (and checked against the game\'s '
             'own code) that no other note describes. What they do is known exactly; the rewrite source has the '
             'details.', '',
             '| Address | Name | What it does |', '|---|---|---|', *out, '']
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print(f'{len(out)} rows written' + (f'; no family description for: {", ".join(unknown)}' if unknown else ''))


if __name__ == '__main__':
    main()
